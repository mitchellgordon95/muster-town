export type TokenKind = "user" | "agent";
/** A row type whose derived columns (generated by the database) a write may leave out. */
type Derived<T, K extends keyof T> = Omit<T, K> & Partial<Pick<T, K>>;
/** A write to a ledger row: the five counters (a counter left out is 0) and the booked adjusted `tokens`; the raw total is derived. */
type Counted<T extends TokenCounts & { rawTokens: number }> = Derived<T, "rawTokens" | TokenCountKind>;
/** A write to a session: its raw `tokens` total is derived from the five counters. */
type SessionWrite = Derived<Session, "tokens" | TokenCountKind>;
type SpentKind = "spentRawTokens" | "spentInput" | "spentOutput" | "spentCacheRead" | "spentCacheWrite5m" | "spentCacheWrite1h";
/** A login token row: `token` is its sha256 hash (`sha256:<hex>`), never the token; `sessionId` set for a per-session agent token. */
export interface TokenRow { token: string; kind: TokenKind; id: string; createdAt: string; sessionId?: string | null }

export class Memberships {
  constructor(private db: DB) {}
  add(m: Membership): void {
    this.db.prepare("INSERT OR IGNORE INTO memberships (roleId, holderKind, holderId) VALUES (?, ?, ?)")
      .run(m.roleId, m.holderKind, m.holderId);
  }
  remove(m: Membership): void {
    this.db.prepare("DELETE FROM memberships WHERE roleId = ? AND holderKind = ? AND holderId = ?")
      .run(m.roleId, m.holderKind, m.holderId);
  }
  forHolder(holderKind: "agent" | "user", holderId: string): Membership[] {
    return this.db.prepare("SELECT * FROM memberships WHERE holderKind = ? AND holderId = ?").all(holderKind, holderId) as Membership[];
  }
  /** Remove every membership of a holder. Returns how many were removed. */
  removeAll(holderKind: "agent" | "user", holderId: string): number {
    return this.db.prepare("DELETE FROM memberships WHERE holderKind = ? AND holderId = ?").run(holderKind, holderId).changes;
  }
  forRole(roleId: string): Membership[] {
    return this.db.prepare("SELECT * FROM memberships WHERE roleId = ?").all(roleId) as Membership[];
  }
  list(): Membership[] {
    return this.db.prepare("SELECT * FROM memberships ORDER BY rowid").all() as Membership[];
  }
}

/** The stored form of a login token (docs/secrets.md "Login tokens"): `sha256:<hex>`. Tokens are random (newToken), so unsalted is enough. */
export function hashToken(token: string): string {
  return `sha256:${createHash("sha256").update(token).digest("hex")}`;
}
const HASHED = "sha256:%";

/**
 * Hash every plaintext login token in place (the boot back-fill; openDb runs it after the migrations). Idempotent: a
 * hashed row is left alone, so every token handed out before keeps working (it is hashed again when presented).
 */
export function hashPlaintextTokens(db: DB): number {
  const rows = db.prepare("SELECT token FROM tokens WHERE token NOT LIKE ?").all(HASHED) as { token: string }[];
  if (!rows.length) return 0;
  const up = db.prepare("UPDATE OR IGNORE tokens SET token = ? WHERE token = ?");
  db.transaction(() => { for (const r of rows) up.run(hashToken(r.token), r.token); })();
  return rows.length;
}

/**
 * Login tokens, stored hashed (sha256): the plaintext is returned once, to whoever the token is created for, and never
 * read back. A session's own token (`createForSession`) is revoked when the session ends (ops.endSession).
 */
export class Tokens {
  /** plaintext of the tokens this process issued through `getOrCreate`, by `kind:id` (a hashed row can't be read back) */
  private issued = new Map<string, string>();
  constructor(private db: DB) {}
  create(kind: TokenKind, id: string, sessionId: string | null = null): string {
    const token = newToken();
    this.db.prepare("INSERT INTO tokens (token, kind, id, createdAt, sessionId) VALUES (?, ?, ?, ?, ?)").run(hashToken(token), kind, id, nowIso(), sessionId);
    return token;
  }
  /** A token for one session of an agent; revoked when that session ends (`revokeSession`). */
  createForSession(agentId: string, sessionId: string): string {
    return this.create("agent", agentId, sessionId);
  }
  /**
   * The token this process issued (or `ensure`d) for this holder, or a new one. Tokens are stored hashed, so one issued before a
   * restart can't be handed out again: after a restart this issues a fresh token (the old ones keep working).
   */
  getOrCreate(kind: TokenKind, id: string): string {
    const key = `${kind}:${id}`;
    const had = this.issued.get(key);
    if (had && this.resolve(had)) return had;
    const token = this.create(kind, id);
    this.issued.set(key, token);
    return token;
  }
  /**
   * Make sure this plaintext token (e.g. the admin token file) resolves to this holder: its hash is inserted if missing.
   * false when the token already belongs to someone else.
   */
  ensure(kind: TokenKind, id: string, token: string): boolean {
    this.db.prepare("INSERT OR IGNORE INTO tokens (token, kind, id, createdAt) VALUES (?, ?, ?, ?)").run(hashToken(token), kind, id, nowIso());
    const row = this.resolve(token);
    const ok = !!row && row.kind === kind && row.id === id;
    if (ok) this.issued.set(`${kind}:${id}`, token); // getOrCreate hands this one out (the dev admin-token route)
    return ok;
  }
  resolve(token: string): TokenRow | undefined {
    const row = this.db.prepare("SELECT * FROM tokens WHERE token = ?").get(hashToken(token)) as TokenRow | undefined;
    if (row) return row;
    // a plaintext row the back-fill hasn't reached (written by an older process): hash it now. Never match a stored hash
    // presented as the token itself, or a copy of the database would hand out logins.
    const legacy = this.db.prepare("SELECT * FROM tokens WHERE token = ? AND token NOT LIKE ?").get(token, HASHED) as TokenRow | undefined;
    if (!legacy) return undefined;
    this.db.prepare("UPDATE OR IGNORE tokens SET token = ? WHERE token = ?").run(hashToken(token), token);
    return { ...legacy, token: hashToken(token) };
  }
  revoke(token: string): void {
    this.db.prepare("DELETE FROM tokens WHERE token IN (?, ?) AND (token = ? OR token NOT LIKE ?)").run(hashToken(token), token, hashToken(token), HASHED);
  }
  /** Revoke a session's own tokens (ops.endSession). Returns how many were removed. */
  revokeSession(sessionId: string): number {
    return this.db.prepare("DELETE FROM tokens WHERE sessionId = ?").run(sessionId).changes;
  }
  /** Revoke every token of a holder. Returns how many were removed. */
  revokeAll(kind: TokenKind, id: string): number {
    for (const k of [...this.issued.keys()]) if (k === `${kind}:${id}`) this.issued.delete(k);
    return this.db.prepare("DELETE FROM tokens WHERE kind = ? AND id = ?").run(kind, id).changes;
  }
}

/**
 * The secret `apiKey` column of `users` (a donor's key) and `bank_inputs` (an input's API key or subscription token),
 * kept at rest as `v1:` ciphertext under the host data key (MUSTER_TOWN_DATA_KEY, docs/secrets.md "Bank secrets at
 * rest"). The AAD is `<table>:<id>`, so a value can't be moved to another row. A host without a data key (it is optional
 * for a self-hosted town) keeps the value in plaintext as before, with a warning, so its Bank still runs; the boot
 * back-fill encrypts it once a key is set. A value that doesn't decrypt (another host's key, e.g. a drill town) reads as null with one warning per
 * row; a legacy plaintext value reads back as is until `encryptPlaintext` (the boot back-fill) converts it.
 */
class SecretColumn {
  private warned = new Set<string>();
  constructor(private readonly db: DB, private readonly table: "users" | "bank_inputs", private readonly what: string, public dataKey: () => string | undefined) {}

  private key(): Buffer {
    const k = dataKeyFrom(this.dataKey());
    if (!k) throw new AppError("conflict", NO_DATA_KEY);
    return k;
  }

  set(id: string, value: string | null): void {
    const key = value ? dataKeyFrom(this.dataKey()) : null;
    if (value && !key) console.warn(`[secrets] ${this.what} ${id}: no MUSTER_TOWN_DATA_KEY on the host, so it is stored in plaintext until one is set`);
    const stored = value && key ? encryptSecret(key, `${this.table}:${id}`, value) : value;
    this.db.prepare(`UPDATE ${this.table} SET apiKey = ?, hasApiKey = ? WHERE id = ?`).run(stored, value ? 1 : 0, id);
  }

  get(id: string): string | null {
    const r = this.db.prepare(`SELECT apiKey FROM ${this.table} WHERE id = ?`).get(id) as { apiKey: string | null } | undefined;
    const v = r?.apiKey ?? null;
    if (!v || !v.startsWith("v1:")) return v; // legacy plaintext until the back-fill runs
    try {
      return decryptSecret(this.key(), `${this.table}:${id}`, v);
    } catch (e) {
      if (!this.warned.has(id)) {
        this.warned.add(id);
        console.warn(`[secrets] ${this.what} ${id} unusable: ${e instanceof AppError ? "no MUSTER_TOWN_DATA_KEY on the host" : "it doesn't decrypt with the host's data key"}`);
      }
      return null;
    }
  }

  /** Encrypt every plaintext value in place (idempotent). Returns how many it converted; 0 without a key. */
  encryptPlaintext(): number {
    let key: Buffer | null;
    try { key = dataKeyFrom(this.dataKey()); } catch { key = null; }
    if (!key) return 0;
    const rows = this.db.prepare(`SELECT id, apiKey FROM ${this.table} WHERE apiKey IS NOT NULL AND apiKey != '' AND apiKey NOT LIKE 'v1:%'`).all() as { id: string; apiKey: string }[];
    const up = this.db.prepare(`UPDATE ${this.table} SET apiKey = ? WHERE id = ? AND apiKey = ?`);
    for (const r of rows) up.run(encryptSecret(key, `${this.table}:${r.id}`, r.apiKey), r.id, r.apiKey);
    return rows.length;
  }
}

/** Users table plus the secret apiKey column (encrypted at rest) that is never part of the User object. */
export class Users extends Table<User> {
  readonly secret: SecretColumn;
  constructor(rawDb: DB, dataKey: () => string | undefined = () => townEnv("DATA_KEY"), onChange?: (u: User) => void) {
    super(rawDb, "users", User, { bool: ["hasApiKey"] }, onChange);
    this.secret = new SecretColumn(rawDb, "users", "donor key of user", dataKey);
  }
  /** Stores the key encrypted; refused (AppError) when the host has no data key. */
  setApiKey(userId: string, apiKey: string | null): User {
    this.secret.set(userId, apiKey);
    return this.require(userId);
  }
  /** Secret. Only the runtime should call this (to set ANTHROPIC_API_KEY for a session). null when unset or unreadable. */
  getApiKey(userId: string): string | null {
    return this.secret.get(userId);
  }
}

/** Bank inputs plus their secret apiKey column (encrypted at rest), never part of the BankInput object. */
export class BankInputs extends Table<BankInput> {
  readonly secret: SecretColumn;
  constructor(rawDb: DB, dataKey: () => string | undefined = () => townEnv("DATA_KEY")) {
    super(rawDb, "bank_inputs", BankInput, { bool: ["hasApiKey"] });
    this.secret = new SecretColumn(rawDb, "bank_inputs", "bank input", dataKey);
  }
  /** Stores the key or token encrypted; refused (AppError) when the host has no data key. */
  setApiKey(inputId: string, apiKey: string | null): BankInput {
    this.secret.set(inputId, apiKey);
    return this.require(inputId);
  }
  /** Secret. Only the runtime should call this. null when unset or unreadable (wrong data key). */
  getApiKey(inputId: string): string | null {
    return this.secret.get(inputId);
  }
}

export class TownMeta {
  constructor(private db: DB, private onChange?: (t: Town) => void) {}
  get(): Town {
    const r = this.db.prepare("SELECT value FROM meta WHERE key = 'town'").get() as { value: string } | undefined;
    return Town.parse(r ? JSON.parse(r.value) : { name: "Muster Town", goal: "" });
  }
  set(t: Partial<Town>): Town {
    const town = Town.parse({ ...this.get(), ...t });
    this.db.prepare("INSERT INTO meta (key, value) VALUES ('town', ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value").run(JSON.stringify(town));
    this.onChange?.(town);
    return town;
  }
  isSet(): boolean {
    return !!this.db.prepare("SELECT 1 FROM meta WHERE key = 'town'").get();
  }
  /** The collective's defaults for every building (stored in the town row; gaps from `BuildingDefaults`, code access on when there's a repo). */
  defaults(): BuildingDefaults {
    const t = this.get();
    return BuildingDefaults.parse({ codeAccess: !!t.workspace, ...t.defaults });
  }
  /** Whether the defaults were ever stored (seed, boot back-fill or PUT /api/town/defaults). */
  hasDefaults(): boolean {
    return !!this.get().defaults;
  }
  /** The runtime Waker's cursor: the last event id it has handled (docs/wakes.md §4 step 4); null before its first boot. */
  wakeCursor(): number | null {
    const r = this.db.prepare("SELECT value FROM meta WHERE key = 'wakeCursor'").get() as { value: string } | undefined;
    return r ? Number(JSON.parse(r.value)) : null;
  }
  setWakeCursor(id: number): void {
    this.db.prepare("INSERT INTO meta (key, value) VALUES ('wakeCursor', ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value").run(JSON.stringify(id));
  }
  /** A small runtime marker kept in `meta` under `key` (e.g. "the reconciliation ran for day X"), null when unset. */
  marker(key: string): string | null {
    const r = this.db.prepare("SELECT value FROM meta WHERE key = ?").get(`marker:${key}`) as { value: string } | undefined;
    return r ? String(JSON.parse(r.value)) : null;
  }
  setMarker(key: string, value: string): void {
    this.db.prepare("INSERT INTO meta (key, value) VALUES (?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value").run(`marker:${key}`, JSON.stringify(value));
  }
  /** collective.json `desks` (stored at seed; defaults when absent). */
  desks(): DesksConfig {
    const r = this.db.prepare("SELECT value FROM meta WHERE key = 'desks'").get() as { value: string } | undefined;
    return DesksConfig.parse(r ? JSON.parse(r.value) : {});
  }
  setDesks(d: Partial<DesksConfig>): DesksConfig {
    const desks = DesksConfig.parse(d);
    this.db.prepare("INSERT INTO meta (key, value) VALUES ('desks', ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value").run(JSON.stringify(desks));
    return desks;
  }
}

/** All repositories. Writes to agents/docs/meetings/buildings/assignments emit the matching ServerMessage. */
export function createRepos(db: DB, changes: Emitter<ServerMessage>) {
  return {
    users: new Users(db),
    roles: new Table<Role>(db, "roles", Role, { json: ["permissions"], bool: ["builtin"] }),
    memberships: new Memberships(db),
    buildings: new Table<Building>(db, "buildings", Building, { json: ["meetings", "lot", "furniture"], bool: ["codeAccess"] }, (building) => changes.emit({ type: "building", building })),
    allocations: new Table<Allocation, Derived<Allocation, SpentKind>>(db, "allocations", Allocation, { bool: ["retired"] }),
    bankInputs: new BankInputs(db),
    bankCredits: new Table<BankCredit, Counted<BankCredit>>(db, "bank_credits", BankCredit),
    bankReservations: new Table<BankReservation>(db, "bank_reservations", BankReservation),
    bankDebits: new Table<BankDebit, Counted<BankDebit>>(db, "bank_debits", BankDebit),
    usage: new Table<UsageEntry, Counted<UsageEntry>>(db, "usage", UsageEntry),
    agents: new Table<Agent>(db, "agents", Agent, { json: ["pos", "deniedPermissions"], bool: ["inheritsOwner"] }, (agent) => changes.emit({ type: "agent", agent })),
    places: new Table<Place>(db, "places", Place, { json: ["pos"] }),
    docs: new Table<Doc>(db, "docs", Doc, { json: ["provenance", "tags", "flagPos"] }, (doc) => changes.emit({ type: "doc", doc })),
    assignments: new Table<Assignment>(db, "assignments", Assignment, { bool: ["offered"], json: ["waitFor", "origin", "pages"] }, (assignment) => changes.emit({ type: "assignment", assignment })),
    messages: new Table<Message>(db, "messages", Message, { json: ["origin"] }),
    meetings: new Table<Meeting>(db, "meetings", Meeting, { json: ["attendeeIds", "summaries", "transcript", "decisions", "brings", "deck"], bool: ["askHumans"] }, (meeting) => changes.emit({ type: "meeting", meeting })),
    sessions: new Table<Session, SessionWrite>(db, "sessions", Session, { json: ["byModel", "origin"] }),
    schedules: new Table<Schedule>(db, "schedules", Schedule, { json: ["dailyAt", "pages", "origin"], bool: ["paused"] }),
    grants: new Table<Grant>(db, "grants", Grant, { json: ["findingsDocIds", "checkpointsDone", "history", "testingPlan"] }),
    keyResults: new Table<KeyResult>(db, "key_results", KeyResult, { json: ["sourceDocIds"] }),
    objectives: new Table<Objective>(db, "objectives", Objective, { json: ["sourceDocIds"] }),
    goals: new Table<Goal>(db, "goals", Goal, { json: ["sourceDocIds"], bool: ["explore"] }),
    goalProposals: new Table<GoalProposal>(db, "goal_proposals", GoalProposal, { json: ["fields", "sourceDocIds"] }),
    goalChanges: new Table<GoalChange>(db, "goal_changes", GoalChange),
    kpis: new Table<Kpi>(db, "kpis", Kpi),
    accessRequests: new Table<AccessRequest>(db, "access_requests", AccessRequest),
    captainRequests: new Table<CaptainRequest>(db, "goal_captain_requests", CaptainRequest),
    skillPins: new Table<SkillPin>(db, "skill_pins", SkillPin, { bool: ["byHuman"] }),
    interrupts: new Table<Interrupt>(db, "interrupts", Interrupt, { bool: ["now"] }),
    tokens: new Tokens(db),
    town: new TownMeta(db),
  };
}
export type Repos = ReturnType<typeof createRepos>;
