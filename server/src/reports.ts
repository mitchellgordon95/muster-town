import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";
import type { Decision, Report, ReportMeta } from "./types.js";
import { buildingDir } from "./town.js";

export function reportsDir(building: string, desk: string): string {
  return path.join(buildingDir(building), "reports", desk);
}

export function runFile(building: string, desk: string, run: number): string {
  return path.join(reportsDir(building, desk), `run-${String(run).padStart(3, "0")}.md`);
}

function iso(v: unknown): string {
  if (!v) return "";
  if (v instanceof Date) return v.toISOString();
  const d = new Date(String(v));
  return isNaN(d.getTime()) ? String(v) : d.toISOString();
}

function parse(file: string, desk: string): Report {
  const raw = fs.readFileSync(file, "utf8");
  const { data, content } = matter(raw);
  const m = content.match(/^#\s+(.+)$/m);
  const runFromName = Number((path.basename(file).match(/run-(\d+)/) || [])[1] || 0);
  return {
    desk: String(data.desk ?? desk),
    run: Number(data.run ?? runFromName),
    started: iso(data.started),
    ended: iso(data.ended),
    verdict: (data.verdict as Report["verdict"]) ?? "continue",
    decision: (data.decision as Decision) ?? "pending",
    note: String(data.note ?? ""),
    cost_usd: data.cost_usd != null ? Number(data.cost_usd) : undefined,
    turns: data.turns != null ? Number(data.turns) : undefined,
    title: m ? m[1].trim() : path.basename(file, ".md"),
    file: path.basename(file),
    body: content,
  };
}

export function listReports(building: string, desk: string): Report[] {
  const dir = reportsDir(building, desk);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => /^run-\d+\.md$/.test(f))
    .sort()
    .map((f) => {
      const r = parse(path.join(dir, f), desk);
      r.file = path.join("reports", desk, f);
      return r;
    });
}

export function latestReport(building: string, desk: string): Report | undefined {
  const all = listReports(building, desk);
  return all[all.length - 1];
}

export function nextRunNumber(building: string, desk: string): number {
  const l = latestReport(building, desk);
  return (l?.run ?? 0) + 1;
}

export function setDecision(building: string, desk: string, run: number, decision: Decision, note = ""): ReportMeta {
  const file = runFile(building, desk, run);
  if (!fs.existsSync(file)) throw new Error(`no report ${file}`);
  const raw = fs.readFileSync(file, "utf8");
  const { data, content } = matter(raw);
  data.decision = decision;
  data.note = note;
  data.decided = new Date().toISOString();
  fs.writeFileSync(file, matter.stringify(content, data));
  const r = parse(file, desk);
  r.file = path.join("reports", desk, path.basename(file));
  return r;
}

export function writeFallbackReport(
  building: string,
  desk: string,
  run: number,
  started: string,
  summary: string,
  error?: string,
): void {
  const file = runFile(building, desk, run);
  if (fs.existsSync(file)) return;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const data = {
    desk,
    run,
    started,
    ended: new Date().toISOString(),
    verdict: "continue",
    decision: "pending",
    note: "",
    autogenerated: true,
  };
  const body = `# Run ${run} — (no report written by agent)

## Summary
The agent finished without writing its report. ${error ? `Error: ${error}` : ""}

## Agent's final message
${summary || "(empty)"}

## Proposal for next run
Re-run with the same direction. Consider lowering scope.
`;
  fs.writeFileSync(file, matter.stringify(body, data));
}

/** Merge extra frontmatter fields (cost, turns, ended) into a run report after the agent wrote it. */
export function stampRun(building: string, desk: string, run: number, fields: Record<string, unknown>): void {
  const file = runFile(building, desk, run);
  if (!fs.existsSync(file)) return;
  const { data, content } = matter(fs.readFileSync(file, "utf8"));
  for (const [k, v] of Object.entries(fields)) if (v !== undefined) data[k] = v;
  if (!data.decision) data.decision = "pending";
  fs.writeFileSync(file, matter.stringify(content, data));
}
